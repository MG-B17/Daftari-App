import 'package:drift/drift.dart';

import 'customers_table.dart';

/// Ledger entry types stored in [Transactions.type].
abstract final class TransactionTypes {
  static const credit = 'credit';
  static const payment = 'payment';
  static const values = {credit, payment};
}

/// A credit (money owed by the customer) or payment (money received) entry.
/// Amounts are always integer piasters, never floating point.
@DataClassName('TransactionRecord')
@TableIndex(name: 'idx_transactions_customer_id', columns: {#customerId})
@TableIndex(name: 'idx_transactions_deleted_at', columns: {#deletedAt})
@TableIndex(
  name: 'idx_transactions_transaction_date',
  columns: {#transactionDate},
)
@TableIndex(
  name: 'idx_transactions_customer_deleted',
  columns: {#customerId, #deletedAt},
)
class Transactions extends Table {
  /// UUID generated by the DAO.
  TextColumn get id => text()();

  TextColumn get customerId =>
      text().references(Customers, #id, onDelete: KeyAction.restrict)();

  // The allowed values are enforced by [customConstraints] below.
  TextColumn get type => text()();

  IntColumn get amountPiasters => integer()();

  TextColumn get note => text().nullable()();

  DateTimeColumn get transactionDate => dateTime()();

  DateTimeColumn get createdAt => dateTime().clientDefault(DateTime.now)();

  DateTimeColumn get updatedAt => dateTime().clientDefault(DateTime.now)();

  DateTimeColumn get deletedAt => dateTime().nullable()();

  /// Monotonic local version used by backup sync.
  IntColumn get localRevision => integer().withDefault(const Constant(1))();

  /// Highest [localRevision] confirmed by cloud backup (`0` means never backed up).
  IntColumn get acknowledgedRevision =>
      integer().withDefault(const Constant(0))();

  DateTimeColumn get syncedAt => dateTime().nullable()();

  @override
  Set<Column> get primaryKey => {id};

  @override
  List<String> get customConstraints => [
    "CHECK (type IN ('credit', 'payment'))",
    'CHECK (amount_piasters > 0)',
  ];
}
