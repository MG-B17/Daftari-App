import 'package:drift/drift.dart';

import 'transactions_table.dart';

/// Audit actions stored in [TransactionAuditLogs.action].
abstract final class TransactionAuditActions {
  static const edit = 'edit';
  static const delete = 'delete';
  static const values = {edit, delete};
}

/// Append-only history of edits and soft deletes. Rows are never updated or
/// removed, so the previous values of every mutation stay available.
@DataClassName('TransactionAuditLog')
@TableIndex(
  name: 'idx_transaction_audit_logs_transaction_id',
  columns: {#transactionId},
)
class TransactionAuditLogs extends Table {
  /// UUID generated by the DAO.
  TextColumn get id => text()();

  TextColumn get transactionId =>
      text().references(Transactions, #id, onDelete: KeyAction.restrict)();

  // The allowed values are written by the DAO only.
  TextColumn get action => text()();

  TextColumn get previousType => text()();

  IntColumn get previousAmountPiasters => integer()();

  TextColumn get previousNote => text().nullable()();

  DateTimeColumn get previousTransactionDate => dateTime()();

  DateTimeColumn get createdAt => dateTime().clientDefault(DateTime.now)();

  /// Monotonic local version used by the future backup sync.
  IntColumn get localRevision => integer().withDefault(const Constant(1))();

  DateTimeColumn get syncedAt => dateTime().nullable()();

  @override
  Set<Column> get primaryKey => {id};
}
