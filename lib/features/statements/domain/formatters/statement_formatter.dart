import '../../../../core/utils/app_date_utils.dart';
import '../../../../core/utils/money_utils.dart';
import '../../../transactions/domain/entities/transaction_entity.dart';
import '../entities/customer_statement_entity.dart';
import '../entities/statement_date_range.dart';

abstract final class StatementFormatter {
  static String format(
    CustomerStatementEntity statement, {
    String locale = 'ar',
  }) {
    final ar = locale.startsWith('ar');
    String money(int amount) =>
        MoneyUtils.formatPiasters(amount, locale: locale);
    String date(DateTime value) =>
        AppDateUtils.formatDate(value, locale: locale);
    final range = switch (statement.range.type) {
      StatementDateRangeType.all => ar ? 'كل المعاملات' : 'All transactions',
      StatementDateRangeType.last30Days => ar ? 'آخر 30 يوم' : 'Last 30 days',
      StatementDateRangeType.thisMonth => ar ? 'هذا الشهر' : 'This month',
      StatementDateRangeType.custom =>
        '${date(statement.range.start!)} – ${date(statement.range.end!)}',
    };
    final phone = statement.customer.phone;
    final lines = <String>[
      ar ? 'دفتري — كشف حساب' : 'Daftari — Account statement',
      '${ar ? 'تاريخ الإصدار' : 'Generated'}: '
          '${date(statement.generatedAt)} '
          '${AppDateUtils.formatTime(statement.generatedAt, locale: locale)}',
      '${ar ? 'العميل' : 'Customer'}: ${statement.customer.name}',
      if (phone != null && phone.trim().isNotEmpty)
        '${ar ? 'الهاتف' : 'Phone'}: $phone',
      '${ar ? 'الرصيد الحالي' : 'Current balance'}: '
          '${money(statement.balancePiasters)}',
      '${ar ? 'الفترة' : 'Period'}: $range',
      '',
      ar ? 'المعاملات' : 'Transactions',
      if (statement.entries.isEmpty)
        ar
            ? 'لا توجد معاملات في هذه الفترة.'
            : 'No transactions in this period.',
      for (final entry in statement.entries)
        '${date(entry.transactionDate)} | '
            '${entry.type == TransactionType.credit ? (ar ? 'آجل' : 'Credit') : (ar ? 'سداد' : 'Payment')}'
            ' | ${money(entry.amountPiasters)}'
            '${entry.note == null || entry.note!.trim().isEmpty ? '' : ' | ${entry.note!.trim()}'}',
      '',
      '${ar ? 'إجمالي الآجل للفترة' : 'Period credit total'}: '
          '${money(statement.periodCreditPiasters)}',
      '${ar ? 'إجمالي السداد للفترة' : 'Period payment total'}: '
          '${money(statement.periodPaymentPiasters)}',
      '',
      ar ? 'تم إنشاء هذا الكشف بواسطة دفتري' : 'Generated by Daftari',
    ];
    return lines.join('\n');
  }
}
