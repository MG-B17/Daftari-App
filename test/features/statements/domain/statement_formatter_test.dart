import 'package:daftariapp/core/utils/app_date_utils.dart';
import 'package:daftariapp/features/statements/domain/entities/statement_date_range.dart';
import 'package:daftariapp/features/statements/domain/formatters/statement_formatter.dart';
import 'package:daftariapp/features/transactions/domain/entities/transaction_entity.dart';
import 'package:flutter_test/flutter_test.dart';

import 'statement_fixtures.dart';

void main() {
  setUpAll(AppDateUtils.initialize);

  test('English text includes identity, dates, notes and exact totals', () {
    final statement = statementFixture(
      entries: [
        statementTransaction(amount: 123456, note: ' Groceries '),
        statementTransaction(
          id: 't2',
          type: TransactionType.payment,
          amount: 101,
        ),
      ],
    );
    final text = StatementFormatter.format(statement, locale: 'en');
    expect(text, startsWith('Daftari — Account statement\n'));
    expect(text, contains('Customer: Test Customer\nPhone: 01012345678'));
    expect(
      text,
      contains(
        'Generated: Nov 20, 2026 '
        '${AppDateUtils.formatTime(statementNow, locale: 'en')}',
      ),
    );
    expect(text, contains('Current balance: 1,233.55 EGP'));
    expect(text, contains('Period: All transactions'));
    expect(text, contains('Nov 20, 2026 | Credit | 1,234.56 EGP | Groceries'));
    expect(text, contains('Nov 20, 2026 | Payment | 1.01 EGP'));
    expect(text, contains('Period credit total: 1,234.56 EGP'));
    expect(text, contains('Period payment total: 1.01 EGP'));
    expect(text, endsWith('Generated by Daftari'));
    expect(text, isNot(contains('Private customer notes')));
  });

  test('Arabic is default and supports regional Arabic locales', () {
    final statement = statementFixture(
      entries: [
        statementTransaction(amount: 101, note: 'بقالة'),
        statementTransaction(
          id: 't2',
          type: TransactionType.payment,
          amount: 102,
        ),
      ],
    );
    for (final locale in ['ar', 'ar_EG']) {
      final text = StatementFormatter.format(statement, locale: locale);
      expect(text, startsWith('دفتري — كشف حساب'));
      expect(text, contains('العميل: Test Customer'));
      expect(text, contains('الهاتف: 01012345678'));
      expect(text, contains('الرصيد الحالي: -0.01 ج.م'));
      expect(text, contains('آجل | 1.01 ج.م | بقالة'));
      expect(text, contains('سداد | 1.02 ج.م'));
      expect(text, contains('إجمالي الآجل للفترة: 1.01 ج.م'));
      expect(text, contains('إجمالي السداد للفترة: 1.02 ج.م'));
      expect(
        text,
        contains(AppDateUtils.formatDate(statementNow, locale: locale)),
      );
      expect(
        text,
        contains(AppDateUtils.formatTime(statementNow, locale: locale)),
      );
      expect(text, endsWith('تم إنشاء هذا الكشف بواسطة دفتري'));
    }
    expect(
      StatementFormatter.format(statement),
      StatementFormatter.format(statement, locale: 'ar'),
    );
  });

  test('empty history has localized message and zero totals', () {
    final statement = statementFixture(phone: null);
    final en = StatementFormatter.format(statement, locale: 'en');
    final ar = StatementFormatter.format(statement);
    expect(en, contains('No transactions in this period.'));
    expect(en, contains('Current balance: 0 EGP'));
    expect(en, contains('Period credit total: 0 EGP'));
    expect(en, contains('Period payment total: 0 EGP'));
    expect(ar, contains('لا توجد معاملات في هذه الفترة.'));
    expect(ar, contains('الرصيد الحالي: 0 ج.م'));
    expect(en, isNot(contains('Phone:')));
    expect(ar, isNot(contains('الهاتف:')));
  });

  test(
    'blank phone and notes are omitted without null text or trailing pipe',
    () {
      final text = StatementFormatter.format(
        statementFixture(
          phone: ' ',
          entries: [statementTransaction(note: ' ')],
        ),
        locale: 'en',
      );
      expect(text, isNot(contains('Phone:')));
      expect(text, isNot(contains('null')));
      expect(text, contains('Credit | 1.01 EGP\n'));
    },
  );

  test('all range labels are localized including custom boundaries', () {
    for (final (range, english, arabic) in [
      (StatementDateRange.all, 'All transactions', 'كل المعاملات'),
      (StatementDateRange.last30Days, 'Last 30 days', 'آخر 30 يوم'),
      (StatementDateRange.thisMonth, 'This month', 'هذا الشهر'),
    ]) {
      final statement = statementFixture(range: range);
      expect(
        StatementFormatter.format(statement, locale: 'en'),
        contains('Period: $english'),
      );
      expect(StatementFormatter.format(statement), contains('الفترة: $arabic'));
    }
    final custom = StatementDateRange.custom(
      start: DateTime(2026, 10, 1),
      end: DateTime(2026, 11, 20),
    );
    for (final locale in ['ar', 'en']) {
      final text = StatementFormatter.format(
        statementFixture(range: custom),
        locale: locale,
      );
      expect(
        text,
        contains(AppDateUtils.formatDate(custom.start!, locale: locale)),
      );
      expect(
        text,
        contains(AppDateUtils.formatDate(custom.end!, locale: locale)),
      );
    }
  });

  test(
    'formatted history stays newest-first and excludes out-of-range entries',
    () {
      final text = StatementFormatter.format(
        statementFixture(
          range: StatementDateRange.thisMonth,
          entries: [
            statementTransaction(
              id: 'old',
              date: DateTime(2026, 10),
              note: 'Excluded',
            ),
            statementTransaction(
              id: 'early',
              date: DateTime(2026, 11, 1),
              note: 'Early',
            ),
            statementTransaction(id: 'latest', note: 'Latest'),
          ],
        ),
        locale: 'en',
      );
      expect(text.indexOf('Latest'), lessThan(text.indexOf('Early')));
      expect(text, isNot(contains('Excluded')));
      expect(text, contains('Current balance: 3.03 EGP'));
      expect(text, contains('Period credit total: 2.02 EGP'));
    },
  );
}
